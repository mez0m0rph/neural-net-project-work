import numpy as np  # для хранения и обработки таблиц чисел
import torch  # умеет считать градиенты (менять веса для уменьшения ошибки)
import torch.nn as nn  # подмодуль внутри torch для нейросетевых функций

# X: [%волокна, %ПЭЭК, %наполнителя2, температура]
X = np.array([
    [10, 80, 10, 23], [10, 70, 20, 23], [20, 70, 10, 23], [20, 60, 20, 23],
    [30, 60, 10, 23], [30, 50, 20, 23], [10, 80, 10, 60], [20, 70, 10, 60],
    [30, 60, 10, 60], [15, 75, 10, 23], [25, 65, 10, 23],
], dtype=np.float32)

# y: [прочность, износостойкость] (измеренные свойства)
y = np.array([
    [45, 30], [42, 28], [55, 25], [50, 22], [63, 18], [58, 16],
    [40, 27], [50, 21], [57, 15], [48, 29], [59, 20],
], dtype=np.float32)

# нормализация (нейросети плохо работают с сырыми разномасштабными числами)
X = (X - X.mean(0)) / X.std(0) # mean - ср. ариф. по каждому столбцу отдельно, std - стандартное отклонение
y_mean, y_std = y.mean(0), y.std(0)
y_n = (y - y_mean) / y_std

# x y - пара "условия эксперимента" -> "результат"

X_t = torch.tensor(X)
y_t = torch.tensor(y_n)

# маленькая сеть: 1 скрытый слой, 4 нейрона (данных мало, большая сеть переобучится)
model = nn.Sequential(
    nn.Linear(X.shape[1], 4),
    nn.Tanh(),
    nn.Linear(4, y.shape[1]),
)

loss_fn = nn.MSELoss()  # функция ошибки - среднеквадратичное отклонение предсказания от факта. 
    # чем ближе предсказание к реальному Y, тем меньше это число

opt = torch.optim.Adam(model.parameters(), lr=0.02, weight_decay=1e-2)
# оптимизатор - алгоритм, который подстраивает веса сети для уменьшения ошибки
# lr - скорость обучения (насколько быстро меняются веса)
# weight_decay - регуляризация (не дает весам стать слишком большими, чтобы сеть не переобучалась на 11 точках)

for epoch in range(300):
    opt.zero_grad()
    pred = model(X_t)
    loss = loss_fn(pred, y_t)
    loss.backward()
    opt.step()
    if epoch % 50 == 0:
        print(f"epoch {epoch}, loss {loss.item():.4f}")

# предсказания на тех же данных (проверка, что сеть вообще чему-то научилась)
pred_real = model(X_t).detach().numpy() * y_std + y_mean
print("\nфакт vs предсказание:")
for i in range(len(y)):
    print(y[i], "->", np.round(pred_real[i], 1))