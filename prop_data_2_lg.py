def get_physics_point(n_points=1000):
    """Генерация плотной сетки значений для проверки физической корректности модели"""
    cf_grid = np.linspace(0.0, 50.0, int(np.sqrt(n_points)))
    length_grid = np.linspace(0.0, 3.0, int(np.sqrt(n_points)))
    cf_mesh, length_mesh = np.meshgrid(cf_grid, length_grid)
    X_phys_raw = np.vstack([cf_mesh.ravel(), length_mesh.ravel()]).T.astype(np.float32)
    X_phys_scaled = scaler_X.transform(X_phys_raw)
    return torch.tensor(X_phys_scaled, dtype=torch.float32)

